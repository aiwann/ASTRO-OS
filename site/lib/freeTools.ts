export type LoveResult = {
  score: number;
  label: string;
  teaser: string;
};

export function loveCompatibility(date1: string, date2: string): LoveResult {
  const lp1 = lifePathNumber(date1);
  const lp2 = lifePathNumber(date2);
  if (!lp1 || !lp2) {
    return { score: 0, label: "—", teaser: "Въведи валидни дати на раждане." };
  }

  const r1 = MASTER_NUMBERS.has(lp1) ? reduce(lp1.toString().split("").reduce((a,b)=>a+Number(b),0)) : lp1;
  const r2 = MASTER_NUMBERS.has(lp2) ? reduce(lp2.toString().split("").reduce((a,b)=>a+Number(b),0)) : lp2;

  // Compatibility matrix logic — combine resonance with friction.
  const harmonious = [
    [1, 5], [1, 7], [2, 6], [2, 8], [3, 5], [3, 9],
    [4, 8], [5, 7], [6, 9], [3, 6], [1, 3], [4, 7],
  ];
  const challenging = [
    [1, 4], [1, 8], [2, 5], [3, 4], [4, 5], [6, 7], [7, 8],
  ];

  const pair = [Math.min(r1, r2), Math.max(r1, r2)];
  let base = 65;
  if (r1 === r2) base = 70;
  if (harmonious.some(([a, b]) => a === pair[0] && b === pair[1])) base = 90;
  if (challenging.some(([a, b]) => a === pair[0] && b === pair[1])) base = 50;

  // Add deterministic variation from the two life paths so different couples don't all get the same score.
  const variation = ((lp1 * 7 + lp2 * 13) % 11) - 5;
  let score = base + variation;
  if (score < 40) score = 40;
  if (score > 95) score = 95;

  let label: string;
  let teaser: string;
  if (score >= 85) {
    label = "Изключителна";
    teaser =
      "Енергиите ви се допълват по начин, който се случва рядко. Има нещо магнетично — но и нещо, което още не виждате един в друг.";
  } else if (score >= 70) {
    label = "Силна";
    teaser =
      "Имате солидна основа за дълготрайна връзка. Зад първото впечатление обаче се крие един кармичен модел, който определя дали ще израствате заедно или ще се повтаряте.";
  } else if (score >= 55) {
    label = "Балансирана";
    teaser =
      "Различни сте — но именно различията ви могат да ви направят по-силни. Има едно ключово напрежение, което, ако го разберете, става ваша най-голяма сила.";
  } else {
    label = "Предизвикателна";
    teaser =
      "Връзката ви е учител, не комфортна зона. Има реални триения, но и реален потенциал — ако и двамата сте готови да видите това, което избягвате.";
  }

  return { score, label, teaser };
}

