const MASTER_NUMBERS = new Set([11, 22, 33]);

export function reduce(n: number): number {
  let value = Math.abs(Math.trunc(n));
  while (value > 9 && !MASTER_NUMBERS.has(value)) {
    value = value
      .toString()
      .split("")
      .reduce((acc, d) => acc + Number(d), 0);
  }
  return value;
}

function parseDate(date: string): { y: number; m: number; d: number } | null {
  if (!date) return null;
  const iso = date.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (iso) {
    return { y: +iso[1], m: +iso[2], d: +iso[3] };
  }
  const dmy = date.match(/^(\d{1,2})[\/.-](\d{1,2})[\/.-](\d{4})$/);
  if (dmy) {
    return { y: +dmy[3], m: +dmy[2], d: +dmy[1] };
  }
  return null;
}

export function lifePathNumber(date: string): number {
  const p = parseDate(date);
  if (!p) return 0;
  const sum =
    p.y
      .toString()
      .split("")
      .reduce((a, b) => a + Number(b), 0) +
    p.m
      .toString()
      .split("")
      .reduce((a, b) => a + Number(b), 0) +
    p.d
      .toString()
      .split("")
      .reduce((a, b) => a + Number(b), 0);
  return reduce(sum);
}

