'use strict';

const { MASTER_SYSTEM_PROMPT } = require('./systemPrompt');

// ============================================================================
//  BUMP PROMPTS — small, focused add-on products (1-2 pages each)
//  All prompts receive `data = { user, geo, natal, numerology }` like mains.
// ============================================================================

function buildUserCtx(data) {
  const { user, natal, numerology: n } = data;
  return `КЛИЕНТ: ${user.name} · ${user.birthDate}${user.birthTime ? ' · ' + user.birthTime : ''} · ${user.birthPlace}
Слънце: ${natal.sun?.sign?.name} (Дом ${natal.sun?.house})
Луна: ${natal.moon?.sign?.name} (Дом ${natal.moon?.house})
Асцендент: ${natal.ascendant?.sign?.name}
Венера: ${natal.planets?.Venus?.sign?.name}, Дом ${natal.planets?.Venus?.house}
Марс: ${natal.planets?.Mars?.sign?.name}, Дом ${natal.planets?.Mars?.house}
Сатурн: ${natal.planets?.Saturn?.sign?.name}, Дом ${natal.planets?.Saturn?.house}
Хирон: ${natal.chiron?.sign?.name}, Дом ${natal.chiron?.house}
Лилит: ${natal.lilith?.sign?.name}, Дом ${natal.lilith?.house}
Южен Възел: ${natal.southNode?.sign?.name || (natal.northNode?.sign?.opposite || 'противоположен на Северния')}
Доминантен елемент: ${natal.dominantElement}
Жизнен Път: ${n?.lifePath} · Съдба: ${n?.destiny} · Душа: ${n?.soulUrge}`;
}

