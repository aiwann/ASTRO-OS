function buildLiteCtx(data) {
  const { user, natal, numerology: n } = data;
  return `КЛИЕНТ: ${user.name} · ${user.birthDate}${user.birthTime ? ' · ' + user.birthTime : ''} · ${user.birthPlace}
Слънце: ${natal.sun?.sign?.name} (Дом ${natal.sun?.house})
Луна: ${natal.moon?.sign?.name} (Дом ${natal.moon?.house})
Асцендент: ${natal.ascendant?.sign?.name}
Венера: ${natal.planets?.Venus?.sign?.name}, Дом ${natal.planets?.Venus?.house}
Марс: ${natal.planets?.Mars?.sign?.name}, Дом ${natal.planets?.Mars?.house}
Луна фаза при раждане: ${natal.moonPhase || 'не е изчислена'}
Доминантен елемент: ${natal.dominantElement}
Жизнен Път: ${n?.lifePath} · Съдба: ${n?.destiny}`;
}

